/**
 * Builds localized blog/forum TS modules from English source + JSON translation overlays.
 * Run: node scripts/part3-generate-locale-posts.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const { enBlogArticles } = await import(pathToFileURL(path.join(root, 'src/data/blog/posts/en-articles.ts')).href);
const { enForumPosts } = await import(pathToFileURL(path.join(root, 'src/data/forum/en-posts.ts')).href);

const LOCALES = ['es', 'de', 'fr'];

function loadOverlay(locale) {
  const file = path.join(root, 'content/part3/translations', `${locale}.json`);
  if (!fs.existsSync(file)) throw new Error(`Missing translation overlay: ${file}`);
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function mergeBlog(en, overlay) {
  const tr = overlay.blog?.[en.slug];
  if (!tr) throw new Error(`Missing blog translation for ${en.slug}`);
  return {
    ...en,
    title: tr.title,
    h1: tr.h1 ?? tr.title,
    tag: tr.tag,
    desc: tr.desc,
    metaTitle: tr.metaTitle ?? tr.title,
    metaDescription: tr.metaDescription ?? tr.desc,
    imageAlt: tr.imageAlt ?? en.imageAlt,
    author: tr.author ?? en.author,
    body: tr.body,
  };
}

function mergeForum(en, overlay, locale) {
  const tr = overlay.forum?.[en.slug];
  if (!tr) throw new Error(`Missing forum translation for ${en.slug}`);
  const disclosure = overlay.forumDisclosure?.[locale] ?? en.body[0];
  return {
    ...en,
    title: tr.title,
    excerpt: tr.excerpt,
    category: tr.category,
    body: [disclosure, ...(tr.body ?? en.body.slice(1))],
    comments: [
      {
        author: tr.commentAuthor ?? en.comments[0]?.author,
        age: '',
        score: 0,
        body: tr.commentBody ?? en.comments[0]?.body,
      },
    ],
    sourceTitle: tr.sourceTitle ?? en.sourceTitle,
  };
}

for (const locale of LOCALES) {
  const overlay = loadOverlay(locale);
  const blogs = enBlogArticles.map((post) => mergeBlog(post, overlay));
  const forums = enForumPosts.map((post) => mergeForum(post, overlay, locale));

  const blogFile = path.join(root, `src/data/blog/posts/${locale}-articles.ts`);
  const forumFile = path.join(root, `src/data/forum/${locale}-posts.ts`);
  const blogName = `${locale}BlogArticles`;
  const forumName = `${locale}ForumPosts`;

  fs.writeFileSync(
    blogFile,
    `// Generated by scripts/part3-generate-locale-posts.mjs — Part 3 editorial translations.\nimport type { BlogPostFull } from '../types';\n\nexport const ${blogName}: BlogPostFull[] = ${JSON.stringify(blogs, null, 2)};\n`,
  );
  fs.writeFileSync(
    forumFile,
    `// Generated by scripts/part3-generate-locale-posts.mjs — Part 3 editorial translations.\nimport type { ForumPost } from './types';\n\nexport const ${forumName}: ForumPost[] = ${JSON.stringify(forums, null, 2)};\n`,
  );
  console.log(`Wrote ${locale}: ${blogs.length} blogs, ${forums.length} forum topics`);
}
