/** Netlify-style redirect rules for static hosts (copied to dist via public/). */
import fs from 'node:fs';
import path from 'node:path';
import { PATH_REDIRECTS } from './redirects.mjs';
import { CHECKOUT_PATH_REDIRECTS } from '../src/config/checkout-redirects.mjs';
import { SITE_URL } from '../src/config/site-url.mjs';

const lines = ['# Generated by scripts/generate-static-redirects.mjs. Do not edit.'];
for (const [from, to] of PATH_REDIRECTS.entries()) {
  lines.push(`${from}  ${to}  301`);
}
for (const [from, to] of CHECKOUT_PATH_REDIRECTS.entries()) {
  lines.push(`${from}  ${to}  302`);
}
// Netlify supports a 4th token (`query=...`); Cloudflare Workers/Pages `_redirects` only allows
// 2–3 tokens. Forum `?category=` / `?sort=` / `?page=` canonicalization is handled in `workers/site.js`
// (and Astro middleware locally) via `resolveForumQueryRedirect`, not in this file.

const out = path.join('public', '_redirects');
fs.writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`Wrote ${lines.length - 1} redirect rules → ${out}`);

const robots = `User-agent: *
Allow: /
Disallow: /go/
Disallow: /es/go/
Disallow: /de/go/
Disallow: /fr/go/

Sitemap: ${SITE_URL}/sitemap.xml
`;
fs.writeFileSync(path.join('public', 'robots.txt'), robots);
console.log(`Wrote public/robots.txt → Sitemap: ${SITE_URL}/sitemap.xml`);

/** Fallback pages when a host serves files instead of `_redirects`. Hover still shows `/go/…`. */
function escapeHtml(value) {
  return value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

const GO_PAGE_COPY = {
  '/go/nba-2k27/': {
    title: 'Continue to NBA2K27 Cheats checkout',
    description:
      'This noindex page redirects you to secure checkout for NBA2K27 Cheats. It is not listed in search.',
    h1: 'Continue to NBA2K27 Cheats',
    h2: 'Secure checkout for NBA2K27 Cheats',
  },
  '/go/hwid-spoofer/': {
    title: 'Continue to HWID Spoofer checkout',
    description:
      'This noindex page redirects you to secure checkout for the HWID Spoofer. It is not listed in search.',
    h1: 'Continue to HWID Spoofer checkout',
    h2: 'Secure checkout for the HWID Spoofer',
  },
  '/go/cloud-dma/': {
    title: 'Continue to Cloud DMA checkout',
    description:
      'This noindex page redirects you to secure checkout for Cloud DMA. It is not listed in search.',
    h1: 'Continue to Cloud DMA checkout',
    h2: 'Secure checkout for Cloud DMA',
  },
  '/go/shop/': {
    title: 'Continue to shop',
    description:
      'This noindex page redirects you to the shop for orders and support. It is not listed in search.',
    h1: 'Continue to shop',
    h2: 'Shop and support',
  },
  '/go/ugc/': {
    title: 'Continue to the UGC checkout page',
    description:
      'This noindex page redirects you to secure checkout for UGC recovery tools. It is not listed in search.',
    h1: 'Continue to the UGC checkout page',
    h2: 'Secure checkout for UGC recovery',
  },
};

let checkoutPages = 0;
for (const [from, to] of CHECKOUT_PATH_REDIRECTS.entries()) {
  if (!from.endsWith('/')) continue;
  const dir = path.join('public', from);
  fs.mkdirSync(dir, { recursive: true });
  const href = escapeHtml(to);
  const jsUrl = JSON.stringify(to);
  const copy = GO_PAGE_COPY[from];
  const title = escapeHtml(copy.title);
  const description = escapeHtml(copy.description);
  const h1 = escapeHtml(copy.h1);
  const h2 = escapeHtml(copy.h2);
  fs.writeFileSync(
    path.join(dir, 'index.html'),
    `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, follow">
<title>${title}</title>
<meta name="description" content="${description}">
<noscript><meta http-equiv="refresh" content="0;url=${href}"></noscript>
<script>var dest=${jsUrl};var extra=location.search?location.search.slice(1):"";if(extra)dest+=(dest.indexOf("?")>=0?"&":"?")+extra;location.replace(dest);</script>
</head>
<body>
<h1>${h1}</h1>
<h2>${h2}</h2>
</body>
</html>
`,
  );
  checkoutPages += 1;
}
console.log(`Wrote ${checkoutPages} checkout redirect pages → public/go/`);
